    private readonly Texture2D _pixel;

    public PixelFont(Texture2D pixel)
    {
        _pixel = pixel;
    }

    public void Draw(SpriteBatch spriteBatch, string text, int x, int y, int scale, Color color)
    {
        int cursorX = x;
        foreach (char raw in text.ToUpperInvariant())
        {
            char c = Glyphs.ContainsKey(raw) ? raw : ' ';
            string[] glyph = Glyphs[c];

            for (int row = 0; row < glyph.Length; row++)
            {
                string line = glyph[row];
                for (int col = 0; col < line.Length; col++)
                {
                    if (line[col] == '1')
                    {
                        spriteBatch.Draw(_pixel, new Rectangle(cursorX + col * scale, y + row * scale, scale, scale), color);
                    }
                }
            }

            cursorX += 6 * scale;
        }
    }
